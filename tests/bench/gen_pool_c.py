#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ApolloCalc-CAS · pool.json -> pool_c.h 生成器（一次性构建工具，非 bench 运行时依赖）

为什么生成独立头文件而不是把数组内联进 bench-c.c
    C 端不解析 JSON（任务书 4.2）：池必须在编译期写死，运行时零解析开销。
    但把 650 条数组直接内联进 bench-c.c 会让该文件无法手工维护——每次重新
    生成都会覆盖手写逻辑。因此生成独立的 pool_c.h（文件头标注 GENERATED），
    bench-c.c 用 #include 引入：效果等价于「写死在源码里」，但两者解耦。
    若不希望新增文件，把本脚本输出整段粘贴进 bench-c.c 亦可。

用法
    python gen_pool_c.py          # 读取同目录 pool.json，写出 pool_c.h
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def is128(item):
    return 1 if "128KB" in item.get("versions", []) else 0


def norm_parse(item):
    if isinstance(item, str):
        return {"src": item, "x": 0.0, "degree": 0, "angle_deg": 0, "is_128kb": 0}
    return {"src": item["src"], "x": 0.0, "degree": 0, "angle_deg": 0,
            "is_128kb": is128(item)}


def norm_eval(item):
    return {"src": item["src"], "x": float(item["x"]), "degree": 0,
            "angle_deg": 0 if item.get("angleMode") == "RAD" else 1,
            "is_128kb": is128(item)}


def norm_solve(item):
    return {"src": item["src"], "x": 0.0, "degree": int(item["degree"]),
            "angle_deg": 0, "is_128kb": is128(item)}


def emit_table(out, cname, entries):
    out.append("static const pool_entry_t %s[] = {" % cname)
    for e in entries:
        out.append('    { "%s", %s, %d, %d, %d },'
                   % (esc(e["src"]), repr(e["x"]), e["degree"],
                      e["angle_deg"], e["is_128kb"]))
    out.append("};")
    out.append("#define %s_N ((int)(sizeof(%s) / sizeof(%s[0])))"
               % (cname, cname, cname))
    out.append("")


def main():
    with open(os.path.join(HERE, "pool.json"), encoding="utf-8") as f:
        pool = json.load(f)

    tables = [
        ("POOL_PARSE", [norm_parse(i) for i in pool["parse"]]),
        ("POOL_EVAL", [norm_eval(i) for i in pool["eval"]]),
        ("POOL_SOLVE", [norm_solve(i) for i in pool["solve"]]),
        ("POOL_EXACT", [norm_solve(i) for i in pool["exact"]]),
    ]
    expect = {"POOL_PARSE": 250, "POOL_EVAL": 250, "POOL_SOLVE": 100, "POOL_EXACT": 50}
    bad = False
    for n, t in tables:
        if len(t) != expect[n]:
            print("ERROR: %s has %d entries, expected %d"
                  % (n, len(t), expect[n]), file=sys.stderr)
            bad = True
    if bad:
        return 1

    maxn = max(len(t) for _, t in tables)
    total = sum(len(t) for _, t in tables)

    out = []
    out.append("/* GENERATED by tests/bench/gen_pool_c.py -- DO NOT EDIT BY HAND.")
    out.append(" * Source: tests/bench/pool.json -- %d entries "
               "(parse %d / eval %d / solve %d / exact %d)."
               % (total, len(tables[0][1]), len(tables[1][1]),
                  len(tables[2][1]), len(tables[3][1])))
    out.append(" * C 端不解析 JSON：池在编译期写死，运行时零解析开销。")
    out.append(" * is_128kb=1 的条目仅 128KB 两版接受（双曲函数等），"
               "64KB 两版在 accept_entry 处过滤。")
    out.append(" */")
    out.append("#ifndef AC_BENCH_POOL_C_H")
    out.append("#define AC_BENCH_POOL_C_H")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *src;       /* 表达式 */")
    out.append("    double      x;         /* eval 用自变量（其余 stage 恒 0） */")
    out.append("    int         degree;    /* solve/exact 用次数（其余 stage 恒 0） */")
    out.append("    int         angle_deg; /* eval 用角度制：1=DEG(缺省) 0=RAD */")
    out.append("    int         is_128kb;  /* 1 = 仅 128KB 两版 */")
    out.append("} pool_entry_t;")
    out.append("")
    out.append("#define POOL_MAX_N %d" % maxn)
    out.append("")
    for n, t in tables:
        emit_table(out, n, t)
    out.append("#endif /* AC_BENCH_POOL_C_H */")

    dst = os.path.join(HERE, "pool_c.h")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d bytes)" % (dst, os.path.getsize(dst)))
    for n, t in tables:
        n128 = sum(1 for e in t if e["is_128kb"])
        print("  %-10s %3d entries (128KB-only %d, 64KB-effective %d)"
              % (n, len(t), n128, len(t) - n128))
    return 0


if __name__ == "__main__":
    sys.exit(main())
