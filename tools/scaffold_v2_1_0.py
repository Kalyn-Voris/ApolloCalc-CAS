# ---------------------------------------------------------------- helpers --

def _under(child: Path, parent: Path) -> bool:
    try:
        child.relative_to(parent)
        return True
    except ValueError:
        return False


def check_target(path: Path) -> None:
    """【红线校验】所有写目标必须在仓库内、且不在上游 C/128KB/ 之下。"""
    rp = path.resolve()
    root = ROOT.resolve()
    if not _under(rp, root):
        raise SystemExit(f"[scaffold] refuse: target outside repo: {rp}")
    if _under(rp, UPSTREAM.resolve()):
        raise SystemExit(f"[scaffold] refuse: target under read-only upstream dir: {rp}")


def read_text(path: Path) -> str:
    # 字节级读入再解码：不做换行翻译，未触及的原始字节逐位保留。
    return path.read_bytes().decode("utf-8")


def write_text(path: Path, text: str) -> None:
    # 本仓库全部文件为 LF / 无 BOM（git ls-files --eol 实测），显式按字节写回。
    path.write_bytes(text.encode("utf-8"))


def patch(text: str, old: str, new: str, label: str) -> str:
    """单点替换；命中数不是恰好 1 就立刻失败（宁可响亮报错不静默错插）。"""
    hits = text.count(old)
    if hits != 1:
        raise SystemExit(
            f"[scaffold] FAIL ({label}): needle hits = {hits}, expected 1:\n{old!r}")
    return text.replace(old, new)


def emit(path: Path, content: str, label: str) -> None:
    """整文件生成。目标已存在但不含本脚本标记 => 拒绝覆盖（非本脚本产物）。"""
    check_target(path)
    if path.exists():
        if SCRIPT_NAME not in read_text(path):
            raise SystemExit(
                f"[scaffold] FAIL: {path} exists but was NOT generated by "
                f"{SCRIPT_NAME}; refusing to overwrite. Move it away first.")
        write_text(path, content)
        print(f"  [gen ] {label}  (overwritten)")
    else:
        write_text(path, content)
        print(f"  [gen ] {label}  (created)")


def apply_edit(path: Path, marker: str, editor, label: str) -> None:
    """幂等编辑：标记已在 => 跳过；否则 editor(text) 单点打补丁后写回。"""
    check_target(path)
    text = read_text(path)
    if marker in text:
        print(f"  [skip] {label}  (marker {marker!r} already present)")
        return
    write_text(path, editor(text))
    print(f"  [edit] {label}")


